import { type Grid, type Palette, raster } from "./pixel";

const OUTLINE = "#14100c";

const fine = (rows: readonly string[], pal: Palette): Grid => {
  const w = Math.max(...rows.map((r) => r.length)) + 2;
  const pad = [".".repeat(w), ...rows.map((r) => `.${r.padEnd(w - 2, ".")}.`), ".".repeat(w)];
  const solid = (y: number, x: number) => {
    const c = pad[y]?.[x];
    return !!c && c !== ".";
  };
  const out = pad.map((row, y) =>
    [...row]
      .map((c, x) =>
        c !== "." ? c : solid(y - 1, x) || solid(y + 1, x) || solid(y, x - 1) || solid(y, x + 1) ? "#" : ".",
      )
      .join(""),
  );
  return raster(out, { ...pal, "#": OUTLINE });
};

